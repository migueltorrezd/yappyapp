import AppKit

/// Why a transcript is being written to a pasteboard. Each purpose carries the
/// nspasteboard.org markers clipboard managers honor (YA-14).
enum PasteboardWritePurpose: Equatable {
    /// Staged only so a synthetic Cmd+V can pick it up. Clipboard managers
    /// should skip it: it is transient and machine-generated.
    case pasteStaging
    /// Auto-paste did not land, so the clipboard copy is the deliverable.
    /// Machine-generated, but the user still needs it for a manual Cmd+V.
    case copyOnlyDelivery
    /// The user pressed COPY on a transcript.
    case userCopy
    /// The user asked for a transcript that was withheld from a secure field.
    /// Concealed, so password-aware managers treat it like a secret.
    case sensitiveCopy
}

enum PasteboardPrivacy {
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    /// Marker types written next to the plain string for each purpose.
    static func markerTypes(for purpose: PasteboardWritePurpose) -> [NSPasteboard.PasteboardType] {
        switch purpose {
        case .pasteStaging:
            return [transientType, autoGeneratedType]
        case .copyOnlyDelivery:
            return [autoGeneratedType]
        case .userCopy:
            return []
        case .sensitiveCopy:
            return [concealedType, autoGeneratedType]
        }
    }

    /// Writes `text` to `pasteboard` with the purpose's markers. Every write is
    /// current-host-only, so a transcript never rides Universal Clipboard to
    /// another device. Returns the pasteboard's changeCount after the write.
    @discardableResult
    static func write(_ text: String, to pasteboard: NSPasteboard, purpose: PasteboardWritePurpose) -> Int {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        pasteboard.setString(text, forType: .string)
        for marker in markerTypes(for: purpose) {
            pasteboard.setData(Data(), forType: marker)
        }
        return pasteboard.changeCount
    }

    /// YA-62: a clipboard item a password manager marked concealed or transient
    /// must never be put back after a paste. Restoring it would re-post the
    /// secret after the manager already cleared it.
    static func isRestorable(itemTypes: [[String]]) -> Bool {
        let protected: Set<String> = [transientType.rawValue, concealedType.rawValue]
        return !itemTypes.contains { types in types.contains(where: protected.contains) }
    }
}
